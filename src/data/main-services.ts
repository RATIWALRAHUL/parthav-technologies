/** Central Service Registry Helpers */
export function getAllMicroServices(): MicroService[] {
  return MAIN_SERVICES.flatMap((main) => main.microServices);
}

export function getMicroService(id: string): MicroService | undefined {
  for (const main of MAIN_SERVICES) {
    const found = main.microServices.find((m) => m.id === id);
    if (found) return found;
  }
  return undefined;
}

export function getMicroServicesByParent(parentSlug: string): MicroService[] {
  const main = MAIN_SERVICES.find(
    (s) => s.categorySlug === parentSlug || s.id === parentSlug
  );
  return main ? main.microServices : [];
}
